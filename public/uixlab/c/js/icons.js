const PAL = { a: '#ffb81f', r: '#ff5964', g: '#36e08b', c: '#5fe4ff', w: '#fffdf3', k: '#0b0d17' };
const cache = new Map();

/** アイコンの canvas を返す。scale は 1 画素を何 CSS px にするか（整数） */
export function icon(name, { color = '#f4ecd4', hi = '#fffdf3', lo = '#0b0d17', scale = 2, cls = '' } = {}) {
  const art = ART[name];
  const cv = document.createElement('canvas');
  const n = art ? art.length : 12;
  cv.width = n;
  cv.height = n;
  cv.className = 'c-ico ' + cls;
  cv.style.width = cv.style.height = `${(n * scale) / 16}rem`;
  cv.setAttribute('aria-hidden', 'true');
  if (!art) return cv;
  const key = `${name}|${color}|${hi}|${lo}`;
  let img = cache.get(key);
  const ctx = cv.getContext('2d');
  if (!img) {
    for (let y = 0; y < n; y++)
      for (let x = 0; x < n; x++) {
        const ch = art[y][x];
        if (ch === '.' || !ch) continue;
        ctx.fillStyle = ch === '#' ? color : ch === '+' ? hi : ch === '-' ? lo : PAL[ch] ?? color;
        ctx.fillRect(x, y, 1, 1);
      }
    cache.set(key, cv);
  } else ctx.drawImage(img, 0, 0);
  return cv;
}

/** ASCII の絵を canvas にする（地図の上のトラックなど） */
export function sprite(rows, pal) {
  const cv = document.createElement('canvas');
  cv.width = rows[0].length;
  cv.height = rows.length;
  const ctx = cv.getContext('2d');
  rows.forEach((r, y) => {
    for (let x = 0; x < r.length; x++) {
      const c = pal[r[x]];
      if (!c) continue;
      ctx.fillStyle = c;
      ctx.fillRect(x, y, 1, 1);
    }
  });
  return cv;
}
