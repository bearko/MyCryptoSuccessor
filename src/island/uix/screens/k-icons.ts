const PAL: Record<string, string> = { a: '#ffb81f', r: '#ff5964', g: '#36e08b', c: '#5fe4ff', w: '#fffdf3', k: '#0b0d17' };

function paint(cv: HTMLCanvasElement, art: string[], color: string, hi: string, lo: string) {
  const g = cv.getContext('2d');
  if (!g) return;
  for (let y = 0; y < 12; y++)
    for (let x = 0; x < 12; x++) {
      const ch = art[y][x];
      if (ch === '.' || !ch) continue;
      g.fillStyle = ch === '#' ? color : ch === '+' ? hi : ch === '-' ? lo : (PAL[ch] ?? color);
      g.fillRect(x, y, 1, 1);
    }
}
/** アイコンの canvas（足した絵。無ければ土台の絵）。scale：1 画素を何 CSS px にするか（rem で伸びる） */
export function kIcon(name: string, o: IcoOpts = {}): HTMLCanvasElement {
  const art = K_ART[name];
  // ここに無い名前：同じ束の s-icons → w-icons（無ければ土台の絵を返す）
  if (!art) return S_ICONS.includes(name) ? sIcon(name, o) : wIcon(name, o);
  const { color = '#f4ecd4', hi = '#fffdf3', lo = '#0b0d17', scale = 2, cls = '' } = o;
  const cv = document.createElement('canvas');
  cv.width = cv.height = 12;
  cv.className = `ux-ico ${cls}`.trim();
  cv.style.width = cv.style.height = `${(12 * scale) / 16}rem`;
  cv.setAttribute('aria-hidden', 'true');
  paint(cv, art, color, hi, lo);
  return cv;
}
/** 紙の上のアイコン（墨の色） */
export const kInk = (name: string, scale = 1) => kIcon(name, { color: '#1a1c2e', hi: '#8a7f5c', lo: '#1a1c2e', scale });

/**
 * アイコンを画像の URL にする（同じ絵を何百も並べる所：スキルツリーのパネルの印。canvas を 1 つずつ作らず、背景の絵として使い回す）。
 * 名前と色ごとに 1 回だけ描く
 */
const urlMemo = new Map<string, string>();
export function kIconUrl(name: string, color = '#f4ecd4', hi = '#fffdf3', lo = '#0b0d17'): string {
  const key = `${name}|${color}|${hi}|${lo}`;
  let u = urlMemo.get(key);
  if (u == null) {
    const cv = kIcon(name, { color, hi, lo, scale: 1 });
    try {
      u = cv.toDataURL();
    } catch {
      u = '';
    }
    urlMemo.set(key, u);
  }
  return u;
}

/** 絵文字 → ドットの絵（この段の画面に出る絵文字。表に無い字は null：呼ぶ側が外すか、決めた代わりの絵にする） */
export const K_EMOJI: Record<string, string> = {
  // 段 UIX4a：全段の表（EMOJI_DOT）に、この段だけの絵を重ねる
  ...EMOJI_DOT,
  '🏆': 'trophy',
  '📜': 'doc',
  '🔍': 'search',
  '📊': 'bars',
  '📈': 'chart',
  '🎯': 'target',
  '🎁': 'gift',
  '💥': 'bomb',
  // 字として読める記号も、この段の今の要素の札では絵にする
  '✦': 'star4',
  '★': 'star',
  '✓': 'check',
  '✔': 'check',
  '▲': 'up',
  '▼': 'down',
};
const EMO_KEYS = Object.keys(K_EMOJI).sort((a, b) => b.length - a.length);
const esc = (k: string) => k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
/** 表にある絵文字（うしろの異体字の印も一緒に取る） */
export const K_EMOJI_RE = new RegExp(`(${EMO_KEYS.map(esc).join('|')})\\uFE0F?`, 'u');
/** 表に無い絵文字も含めて、絵文字らしい字（外すとき） */
export const ANY_EMOJI_RE = /[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}\u{2B00}-\u{2BFF}\u{2190}-\u{21FF}\u{2300}-\u{23FF}\u{FE0F}\u{200D}\u{20E3}]/u;
/** 字の頭の絵文字を外して、絵の名前と残りの字に分ける（「🔒 ブランド力…」→ ['lock', 'ブランド力…']）。頭に無ければ [null, 字] */
export function headEmoji(text: string): [string | null, string] {
  const m = K_EMOJI_RE.exec(text);
  if (m && m.index === 0) return [K_EMOJI[m[1]], text.slice(m[0].length).replace(/^\s+/, '')];
  return [null, text];
}
/** 字の中の絵文字を全部外す（絵は添えない。DOM なしの芯）。「▲」「▼」「★」「✓」など字として読める記号は残す */
export function noEmoji(text: string): string {
  return text
    .replace(/[\u{1F000}-\u{1FAFF}\u{FE0F}\u{200D}\u{20E3}]|[\u{2600}-\u{26FF}]|[\u{2300}-\u{23FF}]|[\u{2B00}-\u{2BFF}]/gu, '')
    .replace(/[ \t]{2,}/g, ' ')
    .replace(/^\s+/, '');
}
/**
 * 今の要素（本体が作った札）の字の中の絵文字を、ドットの絵に替える（字の色に合わせて描く）。表に無い絵文字は外す。
 * 字そのものを書き換えるのは、この段が受け取った要素の中だけ（本体の読み取りには使われない、出したあとの札）
 */
export function dotEmoji(root: HTMLElement, color?: string) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const todo: Text[] = [];
  for (let n = walker.nextNode(); n; n = walker.nextNode()) if (ANY_EMOJI_RE.test(n.textContent ?? '') || K_EMOJI_RE.test(n.textContent ?? '')) todo.push(n as Text);
  for (const n of todo) {
    const host = n.parentElement;
    if (!host || host.closest('canvas, input, textarea')) continue;
    const col = color ?? inkOf(host);
    const frag = document.createDocumentFragment();
    let rest = n.textContent ?? '';
    for (let guard = 0; guard < 64 && rest; guard++) {
      const m = K_EMOJI_RE.exec(rest);
      if (!m) break;
      if (m.index > 0) frag.append(noStray(rest.slice(0, m.index)));
      frag.append(kIcon(K_EMOJI[m[1]], { color: col, hi: col, lo: col === '#1a1c2e' ? '#8a7f5c' : '#0b0d17', scale: 1, cls: 'uxk-emo' }));
      rest = rest.slice(m.index + m[0].length);
    }
    if (rest) frag.append(noStray(rest));
    n.replaceWith(frag);
  }
}
/** 表に無い絵文字（色つきの絵の字）は外す。「▲▼★✓→」などの記号は、表で絵に替わったあとなので残らない */
const noStray = (text: string) => text.replace(/[\u{1F000}-\u{1FAFF}\u{FE0F}\u{200D}\u{20E3}]/gu, '');
/** 字の色の明るさ（暗い字＝紙の上：墨の絵。明るい字＝板の上：紙の色の絵） */
function inkOf(e: Element): string {
  const m = /rgba?\((\d+),\s*(\d+),\s*(\d+)/.exec(getComputedStyle(e).color);
  if (!m) return '#f4ecd4';
  const l = (Number(m[1]) * 299 + Number(m[2]) * 587 + Number(m[3]) * 114) / 1000;
  if (l < 110) return '#1a1c2e';
  return `rgb(${m[1]}, ${m[2]}, ${m[3]})`;
}
