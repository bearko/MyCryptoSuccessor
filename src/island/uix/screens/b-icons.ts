const PAL: Record<string, string> = { a: '#ffb81f', r: '#ff5964', g: '#36e08b', c: '#5fe4ff', w: '#fffdf3', k: '#0b0d17' };
/** この段で足したアイコンの名前 */
export const B_ICONS = Object.keys(B_ART);
export interface BIconOpts {
  color?: string;
  hi?: string;
  lo?: string;
  scale?: number;
  cls?: string;
}
/** アイコンの canvas。scale：1 画素を何 CSS px にするか（rem で伸びる） */
export function bIcon(name: string, o: BIconOpts = {}): HTMLCanvasElement {
  const art = B_ART[name];
  if (!art) return S_ICONS.includes(name) ? sIcon(name, o) : wIcon(name, o);
  const { color = '#f4ecd4', hi = '#fffdf3', lo = '#0b0d17', scale = 2, cls = '' } = o;
  const cv = document.createElement('canvas');
  cv.width = cv.height = 12;
  cv.className = `ux-ico ${cls}`.trim();
  cv.style.width = cv.style.height = `${(12 * scale) / 16}rem`;
  cv.setAttribute('aria-hidden', 'true');
  const g = cv.getContext('2d');
  if (!g) return cv;
  for (let y = 0; y < 12; y++)
    for (let x = 0; x < 12; x++) {
      const ch = art[y][x];
      if (ch === '.' || !ch) continue;
      g.fillStyle = ch === '#' ? color : ch === '+' ? hi : ch === '-' ? lo : (PAL[ch] ?? color);
      g.fillRect(x, y, 1, 1);
    }
  return cv;
}
/** 紙・琥珀の面の上のアイコン（墨の色） */
export const bInk = (name: string, scale = 1) => bIcon(name, { color: '#1a1c2e', hi: '#8a7f5c', lo: '#1a1c2e', scale });
/** 弱い色のアイコン（添え書きの頭） */
export const bDim = (name: string, scale = 1) => bIcon(name, { color: '#97a1cf', hi: '#f4ecd4', lo: '#3a4266', scale });
