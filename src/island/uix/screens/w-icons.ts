const PAL: Record<string, string> = { a: '#ffb81f', r: '#ff5964', g: '#36e08b', c: '#5fe4ff', w: '#fffdf3', k: '#0b0d17' };
/** アイコンの canvas（足した絵。無ければ土台の絵）。scale：1 画素を何 CSS px にするか（rem で伸びる） */
export function wIcon(name: string, o: IcoOpts = {}): HTMLCanvasElement {
  const art = W_ART[name];
  if (!art) return uxIcon(name, o);
  const { color = '#f4ecd4', hi = '#fffdf3', lo = '#0b0d17', scale = 2, cls = '' } = o;
  const cv = document.createElement('canvas');
  cv.width = cv.height = 12;
  cv.className = `ux-ico ${cls}`.trim();
  cv.style.width = cv.style.height = `${(12 * scale) / 16}rem`;
  cv.setAttribute('aria-hidden', 'true');
  const g = cv.getContext('2d');
  if (!g) return cv;
  for (let y = 0; y < 12; y++)
    for (let x = 0; x < 12; x++) {
      const ch = art[y][x];
      if (ch === '.' || !ch) continue;
      g.fillStyle = ch === '#' ? color : ch === '+' ? hi : ch === '-' ? lo : (PAL[ch] ?? color);
      g.fillRect(x, y, 1, 1);
    }
  return cv;
}
