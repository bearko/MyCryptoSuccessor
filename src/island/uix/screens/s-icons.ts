const PAL: Record<string, string> = { a: '#ffb81f', r: '#ff5964', g: '#36e08b', c: '#5fe4ff', w: '#fffdf3', k: '#0b0d17' };
/** この段で足したアイコンの名前 */
export const S_ICONS = Object.keys(ART);
export interface IconOpts {
  color?: string;
  hi?: string;
  lo?: string;
  scale?: number;
  cls?: string;
}
/** アイコンの canvas（土台にある名前は土台の絵）。scale：1 画素を何 CSS px にするか（整数） */
export function sIcon(name: string, o: IconOpts = {}): HTMLCanvasElement {
  const art = ART[name];
  if (!art) return uxIcon(UX_ICONS.includes(name) ? name : 'note', o);
  const { color = '#f4ecd4', hi = '#fffdf3', lo = '#0b0d17', scale = 2, cls = '' } = o;
  const cv = document.createElement('canvas');
  cv.width = 12;
  cv.height = 12;
  cv.className = `ux-ico ${cls}`.trim();
  cv.style.width = cv.style.height = `${(12 * scale) / 16}rem`;
  cv.setAttribute('aria-hidden', 'true');
  const g = cv.getContext('2d');
  if (!g) return cv;
  for (let y = 0; y < 12; y++)
    for (let x = 0; x < 12; x++) {
      const ch = art[y][x];
      if (ch === '.' || !ch) continue;
      g.fillStyle = ch === '#' ? color : ch === '+' ? hi : ch === '-' ? lo : (PAL[ch] ?? color);
      g.fillRect(x, y, 1, 1);
    }
  return cv;
}
/** 紙の上のアイコン（墨の色） */
export const inkIcon = (name: string, scale = 1) => sIcon(name, { color: '#1a1c2e', hi: '#8a7f5c', lo: '#1a1c2e', scale });
