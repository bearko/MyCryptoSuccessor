// i18n-check: skip — Japanese rarity names switch by language; the rest are data keys.
import raw from '../generated/catalog.json';
import content from './content.json';
import { isEn } from '../i18n';

export const RARITIES = ['Common', 'Uncommon', 'Rare', 'Epic', 'Legendary'] as const;
export type Rarity = (typeof RARITIES)[number];

/** Rarity names for display (Japanese katakana, or the English names). */
export const RARITY_JA: Record<Rarity, string> = isEn
  ? { Common: 'Common', Uncommon: 'Uncommon', Rare: 'Rare', Epic: 'Epic', Legendary: 'Legendary' }
  : { Common: 'コモン', Uncommon: 'アンコモン', Rare: 'レア', Epic: 'エピック', Legendary: 'レジェンド' };

export const RARITY_COLOR: Record<Rarity, string> = {
  Common: '#b9b9b9',
  Uncommon: '#63d471',
  Rare: '#4fa8ff',
  Epic: '#c77dff',
  Legendary: '#ffb627',
};
export type Family = keyof typeof content.families;
export const FAMILIES = Object.fromEntries(
  Object.entries(content.families).map(([k, f]) => [k, { name: isEn ? f.nameEn : f.name, priceMult: f.priceMult }]),
) as Record<Family, { name: string; priceMult: number }>;

export interface Extension {
  id: number;
  name: string;
  rarity: Rarity;
  rarityIndex: number;
  seriesIndex: number;
  seriesName: string;
  family: Family;
  /** The "真" re-release of a Legendary (rarer, pricier, own art). */
  shin: boolean;
  skill: string;
  image: string;
}


/** Sprite sheets generated by scripts/sync-assets.mjs, keyed by sheet name (e.g. "ext-0"). */
export const atlases = raw.atlases as Record<string, { url: string; cols: number; rows: number; cell: number }>;

type RawSeries = (typeof raw.series)[number];

/** Every extension series in the asset database (Legacy and Modern). */
export const allSeries: RawSeries[] = raw.series;

/** The series the game currently uses, in skill-tree order (see content.json). */
export const series = content.activeSeries.map(({ key, family }, seriesIndex) => {
  const s = raw.series.find((x) => x.expansion === 'legacy' && x.key === key) ?? raw.series.find((x) => x.key === key);
  if (!s) throw new Error(`series not in catalog: ${key}`);
  const toExt = (e: (typeof s.items)[number]): Extension => ({
    id: e.id,
    name: isEn ? e.nameEn : e.name,
    rarity: e.rarity as Rarity,
    rarityIndex: RARITIES.indexOf(e.rarity as Rarity),
    seriesIndex,
    seriesName: isEn ? s.nameEn : s.name,
    family: family as Family,
    shin: e.shin,
    skill: isEn ? e.skillEn : e.skill,
    image: e.image,
  });
  // One item per rarity, Common → Legendary (series with variants use the first of each rarity).
  const items = RARITIES.map((r) => {
    const e = s.items.find((i) => i.rarity === r && !i.shin);
    if (!e) throw new Error(`series ${key} has no ${r}`);
    return toExt(e);
  });
  const shinRaw = s.items.find((i) => i.shin);
  return { key: s.key, name: isEn ? s.nameEn : s.name, family: family as Family, items, shin: shinRaw ? toExt(shinRaw) : null };
});

export const extensionById = new Map<number, Extension>(
  series.flatMap((s) => (s.shin ? [...s.items, s.shin] : s.items)).map((e) => [e.id, e]),
);

export function getExtension(id: number): Extension {
  const e = extensionById.get(id);
  if (!e) throw new Error(`unknown extension ${id}`);
  return e;
}

const facesRight = new Set<number>(content.facesRightIds);
/** The hero's sprite faces right (most face left). */
export const heroFacesRight = (id: number) => facesRight.has(id);

export const heroById = new Map(raw.heroes.map((h) => [h.id, h]));
export const audioFiles = raw.audio as Record<string, string>;
